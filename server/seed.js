/* A real, openable PDF, built here rather than shipped as a binary blob. The
   documents screen offers these for download, and a file that will not open is
   a worse demo than no file at all. */
function placeholderPdf(title) {
  const text = `(${title.replace(/[()\\]/g, '')}) Tj`;
  const objs = [
    '<</Type/Catalog/Pages 2 0 R>>',
    '<</Type/Pages/Kids[3 0 R]/Count 1>>',
    '<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]/Resources<</Font<</F1 5 0 R>>>>/Contents 4 0 R>>',
    null,   // filled below: the content stream
    '<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>',
  ];
  const stream = `BT /F1 16 Tf 60 780 Td ${text} ET\n`
    + 'BT /F1 11 Tf 60 750 Td (Placeholder document generated by the Glovels demo server.) Tj ET\n'
    + 'BT /F1 11 Tf 60 732 Td (Replace it by uploading the real file on the Documents screen.) Tj ET';
  objs[3] = `<</Length ${stream.length}>>\nstream\n${stream}\nendstream`;

  let out = '%PDF-1.4\n';
  const offsets = [];
  objs.forEach((o, i) => {
    offsets.push(out.length);
    out += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`
    + offsets.map(o => String(o).padStart(10, '0') + ' 00000 n \n').join('');
  out += `trailer\n<</Size ${objs.length + 1}/Root 1 0 R>>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

