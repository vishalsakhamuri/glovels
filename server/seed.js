/*
 * Three programme names shipped with `&amp;` written into them — double-escaped
 * when the site was first generated — and rendered on the home page as the
 * literal text "AI &amp; Machine Learning". Decoding on the way in fixes the
 * seed; this repairs a database that already has them, once, on start-up.
 *
 * It only touches a value that actually changes when decoded, so it is a no-op
 * on every later boot and cannot mangle a name that legitimately contains an
 * ampersand.
 */
function repairEntities(db) {
  const decode = decodeEntities;
  let n = 0;
  db.programmes(true).forEach(r => {
    const fixed = {
      program: decode(r.program), university: decode(r.university),
      city: decode(r.city), field: decode(r.field),
    };
    if (fixed.program === r.program && fixed.university === r.university
        && fixed.city === (r.city || '') && fixed.field === (r.field || '')) return;
    db.saveProgramme({
      id: r.id, program: fixed.program, university: fixed.university,
      city: fixed.city, country: r.country, level: r.level, field: fixed.field,
      band: r.band, isPublic: !!r.is_public, fit: r.fit, totalInr: r.total_inr,
      url: r.url, active: !!r.active, featured: !!r.featured,
      featureSort: r.feature_sort || 0,
      intakes: (() => { try { return JSON.parse(r.intakes); } catch (e) { return []; } })(),
    }, 'entity repair');
    n++;
  });
  if (n) db.log('system', 'programme names repaired', n + ' had &amp; written into them');
  return n;
}

const decodeEntities = s => String(s == null ? '' : s)
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ');

function seedCatalogue({ db, catalogue, countries }) {
  if (db.programmes(true).length) return repairEntities(db) ? 0 : 0;
  /* The entry requirements come in with the destination. Everything that is
     not code/name/flag/region is a fact the finder's Requirements panel shows,
     and it is seeded here so the office can edit it from day one rather than
     finding an empty form. */
  const FACT_KEYS = ['minCgpaPublic', 'minCgpaPrivate', 'degreeRule', 'backlogRule',
    'extraNote', 'tests', 'fundsLabel', 'fundsInr', 'fundsNote', 'livingInr',
    'workRights', 'deadlineNote', 'documents', 'hasPublicTrack', 'tuitionFree'];
  Object.values(countries || {}).forEach((c, i) => {
    const facts = {};
    FACT_KEYS.forEach(k => { if (c[k] !== undefined) facts[k] = c[k]; });
    db.saveCountry({
      code: c.code, name: c.name, flag: c.flag, region: c.region || '',
      sort: i * 10, facts,
    });
  });
  /* Decoded on the way in, not repaired afterwards. catalogue.json is
     regenerated by build_portal.py from the page, which carries the
     double-escaped names — so fixing the file is undone by the next build, and
     the only durable place is here, where every import passes through. */
  catalogue.forEach(p => db.saveProgramme(Object.assign({}, p, {
    program: decodeEntities(p.program),
    university: decodeEntities(p.university),
    city: decodeEntities(p.city),
    field: decodeEntities(p.field),
  }), 'initial import'));
  db.log('system', 'catalogue imported',
    catalogue.length + ' programmes, ' + Object.keys(countries || {}).length + ' destinations');
  return catalogue.length;
}

/*
 * The six posts that were already on the site, brought in as drafts.
 *
 * They are static HTML files carrying a headline, a lead paragraph and a note
 * to ourselves where the article should be. Read once, on a database that has
 * no posts yet, so the blog screen opens on six half-written posts to finish
 * rather than on an empty list — and so the titles and descriptions somebody
 * wrote for search do not have to be typed again.
 *
 * Drafts, every one. None of them has a body, and a published post with no
 * words is a headline with a URL on it.
 */
function seedPosts({ db, root }) {
  if (db.allPosts().length) return 0;
  const dir = path.join(root, 'post');
  let files = [];
  try { files = fs.readdirSync(dir).filter(f => f.endsWith('.html') && !f.startsWith('_')); }
  catch (e) { return 0; }

  const pick = (html, re) => { const m = re.exec(html); return m ? m[1] : ''; };
  const unent = s => decodeEntities(String(s || '')).replace(/\s+/g, ' ').trim();
  let n = 0;

  for (const f of files.sort()) {
    let html;
    try { html = fs.readFileSync(path.join(dir, f), 'utf8'); } catch (e) { continue; }
    const slug = f.slice(0, -5);
    const title = unent(pick(html, /<h1>([\s\S]*?)<\/h1>/))
      || unent(pick(html, /<title>([\s\S]*?)(?: \| Glovels)?<\/title>/));
    if (!title) continue;
    const desc = unent(pick(html, /<meta name="description" content="([^"]*)"/));
    const lead = unent(pick(html, /<p class="lead">([\s\S]*?)<\/p>/));
    /* The dateline reads "2026-07-16 &middot; 7 min". Only the date is worth
       keeping — the reading time is computed from the words once there are
       any. */
    const when = pick(html, /<h1>[\s\S]*?<\/h1><p>(\d{4}-\d{2}-\d{2})/);

    db.addPost({
      slug, title,
      excerpt: lead || desc,
      body: '',
      status: 'draft',
      metaTitle: '',
      metaDesc: desc,
      keywords: '',
      author: '',
      createdAt: when ? when + 'T09:00:00.000Z' : undefined,
      updatedBy: 'imported from the site',
    });
    n++;
  }
  if (n) db.log('system', 'blog imported', n + ' posts from the pages already on the site');
  return n;
}

/*
 * Two numbers that stopped making sense when the results grew tabs.
 *
 * A visitor who has typed nothing sees a sample of the catalogue. It used to
 * be one mixed column — three public rows and two private ones, five rows,
 * fine. Then private and public were split into their own tabs, and the tab
 * that opens by default opens on two rows: not a sample, a shrug. The list
 * scrolls, so the rest cost nothing to show.
 *
 * The shipped defaults are changed in content.json, which fixes it for a
 * database that has never had the Finder screen saved. This is for the ones
 * that have: it corrects the pair ONLY if it is still exactly the pair we
 * shipped, and it runs once, so an office that deliberately sets three and two
 * tomorrow keeps them.
 */
function bumpBrowseCaps({ db, content }) {
  if (db.content('finderCapsV2')) return false;
  db.setContent('finderCapsV2', { done: true }, 'system');
  const f = db.content('finder');
  if (!f || typeof f !== 'object') return false;
  if (Number(f.browsePublic) !== 3 || Number(f.browsePrivate) !== 2) return false;
  const next = Object.assign({}, f, { browsePublic: 12, browsePrivate: 24 });
  db.setContent('finder', next, 'system');
  db.log('system', 'browse sample widened',
    'the results split into two tabs, and the private tab opened on two rows');
  return true;
}

/*
 * Services shipped since this database was seeded.
 *
 * content.json is read once, on the first run. After that the database is the
 * truth — which is right, because the office edits these from the Home page
 * screen and a redeploy must not undo that. The cost is that a service added
 * to the shipped list after a deployment exists nowhere on that deployment,
 * and there is no message anywhere saying so.
 *
 * This adds only the ids the database has never seen, and never touches one it
 * already has: a price the office changed, a description they rewrote, or a
 * service they deliberately hid all survive. New arrivals come in hidden —
 * `active: false` — because a service on the site with a price of "on request"
 * and nobody briefed to answer is worse than one that is not there yet. The
 * office turns each on when it is ready to sell.
 */
function addMissingServices({ db, content }) {
  const shipped = (content && content.services && content.services.items) || [];
  if (!shipped.length) return 0;
  const live = db.content('services');
  if (!live || !Array.isArray(live.items)) return 0;   /* first run seeds it whole */

  /* Two things have to be true before a service is added: the database has
     never had it, AND we have never offered it before.
     
     The second half matters more than it looks. Without it, a service the
     office deliberately deleted comes back on the next deploy, hidden, and
     comes back again on the one after that — for ever, because "not in the
     database" is exactly what deleting it achieved. The record of what has
     been offered is what tells those two states apart. */
  const offered = new Set(((db.content('servicesOffered') || {}).ids) || []);
  const have = new Set(live.items.map(x => String(x.id)));
  const fresh = shipped
    .filter(x => !have.has(String(x.id)) && !offered.has(String(x.id)))
    .map(x => Object.assign({}, x, { active: false }));

  /* Written whether or not anything was added, so the first run after this
     ships does not treat every existing service as new next time. */
  db.setContent('servicesOffered',
    { ids: shipped.map(x => String(x.id)) }, 'system');
  if (!fresh.length) return 0;

  /* Tabs too, or a service in a new category is in the database and on no
     screen — the chips are markup and the grid filters by them. */
  const tabs = (live.tabs || []).slice();
  const tabKeys = new Set(tabs.map(t => String(t.key)));
  ((content.services.tabs) || []).forEach(t => {
    if (!tabKeys.has(String(t.key))) tabs.push(t);
  });

  db.setContent('services', { tabs, items: live.items.concat(fresh) }, 'system');
  db.log('system', 'new services available',
    fresh.length + ' added, hidden until the office turns them on: '
    + fresh.map(x => x.name).join(', '));
  return fresh.length;
}

