/*
 * The three ways in under ₹5,000, on a database that was seeded before they
 * existed.
 *
 * Same rule as the services above, and the same reason: content.json is read
 * once, on the first run, and after that the database is the truth because the
 * office edits these prices. So a package shipped later exists nowhere on a
 * running deployment — and this one is not a nice-to-have, it is the whole
 * bottom of the price ladder.
 *
 * Unlike a new service, these go on VISIBLE. A hidden ₹99 card is the same as
 * no ₹99 card, there is no price to get wrong (it is written here), and nobody
 * needs briefing to sell it — that is the point of a tier the machine
 * delivers. The `entryTiers` flag records that they have been offered, so a
 * package the office deliberately deletes stays deleted.
 */
function addEntryTiers({ db, content }) {
  const shipped = ((content && content.packages && content.packages.items) || [])
    .filter(p => Number(p.matches || 0) > 0);
  if (!shipped.length) return 0;
  const live = db.content('packages');
  if (!live || !Array.isArray(live.items)) return 0;   /* first run seeds it whole */

  const offered = new Set(((db.content('entryTiers') || {}).ids) || []);
  const have = new Set(live.items.map(x => String(x.id)));
  const fresh = shipped.filter(x => !have.has(String(x.id)) && !offered.has(String(x.id)));

  /* Written whether or not anything was added, so this never runs twice over
     the same package. */
  db.setContent('entryTiers', { ids: shipped.map(x => String(x.id)) }, 'system');
  if (!fresh.length) return 0;

  /* In front of everything they undercut. `sort` is renumbered per tab by the
     content layer, so what matters here is the order of the array. */
  const items = fresh.concat(live.items);
  db.setContent('packages', Object.assign({}, live, { items }), 'system');
  db.log('system', 'entry packages added',
    fresh.map(x => x.title + ' (₹' + x.priceInr + ')').join(', ')
    + ' — delivered by the matcher, no counsellor in the loop');
  return fresh.length;
}

function openOnRequestServices({ db }) {
  if (db.content('servicesOnRequestV1')) return 0;
  db.setContent('servicesOnRequestV1', { done: true }, 'system');

  const live = db.content('services');
  if (!live || !Array.isArray(live.items)) return 0;

  let n = 0;
  const items = live.items.map(x => {
    const untouched = x.active === false
      && !Number(x.priceInr)
      && !x.isFree
      && /on request/i.test(String(x.priceLabel || ''));
    if (!untouched) return x;
    n++;
    return Object.assign({}, x, { active: true });
  });
  if (!n) return 0;

  db.setContent('services', { tabs: live.tabs, items }, 'system');
  db.log('system', 'services opened',
    n + ' priced on request \u2014 the button asks a counsellor');
  return n;
}

/*
 * The six posts, written into the drafts that were waiting for them.
 *
 * seedPosts imported the titles off the shipped pages as empty drafts, and
 * would not run again once any post existed — so a body written later reached a
 * fresh database and nowhere else. This fills a draft whose body is STILL
 * EMPTY, and touches nothing else.
 *
 * Never overwrites. A post the office has started writing has a body, and a
 * body means hands off, whatever we shipped. A post they published is left
 * alone for the same reason.
 *
 * They arrive as drafts, not published. The words are ours to supply; the
 * decision to put them on the site belongs to the person whose name is at the
 * bottom of it.
 */
function fillEmptyPosts({ db, root }) {
  let shipped = [];
  try {
    shipped = JSON.parse(fs.readFileSync(path.join(root, 'posts.json'), 'utf8'));
  } catch (e) { return 0; }
  if (!Array.isArray(shipped) || !shipped.length) return 0;

  const have = db.allPosts();
  let n = 0;

  for (const s of shipped) {
    const row = have.find(x => x.slug === s.slug);
    if (!row) continue;
    if (String(row.body || '').trim()) continue;      /* somebody has written */

    db.updatePost(row.id, {
      slug: row.slug,
      title: s.title || row.title,
      excerpt: s.excerpt || row.excerpt || '',
      body: s.body || '',
      cover: row.cover || '',
      author: row.author || '',
      tag: row.tag || '',
      status: 'draft',
      metaTitle: row.meta_title || '',
      metaDesc: s.metaDescription || row.meta_desc || '',
      keywords: row.keywords || '',
      ogImage: row.og_image || '',
      readMins: Math.max(1, Math.round(String(s.body || '').split(/\s+/).length / 200)),
      publishedAt: row.published_at || '',
      updatedBy: 'system',
    });
    n++;
  }

  if (n) {
    db.log('system', 'blog posts written',
      n + ' draft(s) filled in \u2014 read them and press Publish');
  }
  return n;
}

